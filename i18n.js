let idiomaAtual = localStorage.getItem('user_lang') || 'pt';
let moedaAtual = localStorage.getItem('user_currency') || 'EUR';

const taxasCambio = { EUR: 1.0, BRL: 5.50, USD: 1.08, GBP: 0.85 };
const simbolosMoeda = { EUR: '€', BRL: 'R$', USD: '$', GBP: '£' };

function mudarIdioma(lang) {
  idiomaAtual = lang;
  localStorage.setItem('user_lang', lang);
  aplicarTraducaoInterface();
}

function mudarMoeda(moeda) {
  moedaAtual = moeda;
  localStorage.setItem('user_currency', moeda);
  // Se a página possuir a função de renderizar vitrine/preços, ela é disparada aqui
  if (typeof window.atualizarPrecosMoeda === 'function') {
    window.atualizarPrecosMoeda();
  }
}

function aplicarTraducaoInterface() {
  const selIdioma = document.getElementById('selectIdioma');
  const selMoeda = document.getElementById('selectMoeda');
  
  if (selIdioma) selIdioma.value = idiomaAtual;
  if (selMoeda) selMoeda.value = moedaAtual;

  const t = traducoes[idiomaAtual] || traducoes['pt'];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const chave = el.getAttribute('data-i18n');
    if (t[chave]) el.innerHTML = t[chave];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const chave = el.getAttribute('data-i18n-placeholder');
    if (t[chave]) el.placeholder = t[chave];
  });
}

// Executa automaticamente assim que o script carrega na página
document.addEventListener("DOMContentLoaded", () => {
  aplicarTraducaoInterface();
});