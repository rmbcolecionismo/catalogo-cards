let idiomaAtual = localStorage.getItem('idioma_app') || 'pt-BR';
let moedaAtual = localStorage.getItem('moeda_app') || 'BRL';

function mudarIdioma(novoIdioma) {
  idiomaAtual = novoIdioma;
  localStorage.setItem('idioma_app', novoIdioma);
  aplicarTextosIdioma();
}

function mudarMoeda(novaMoeda) {
  moedaAtual = novaMoeda;
  localStorage.setItem('moeda_app', novaMoeda);
  if (typeof renderizarAtivo === 'function') {
    renderizarAtivo();
  }
}

function aplicarTextosIdioma() {
  const t = traducoes[idiomaAtual] || traducoes['pt-BR'];
  
  // Atualiza os elementos se existirem na tela
  const setElementText = (id, text) => { const el = document.getElementById(id); if (el) el.innerText = text; };

  setElementText('navInicio', t.inicio);
  setElementText('linkCardeneta', t.cardeneta);
  setElementText('linkVitrine', t.vitrine);
  setElementText('linkPerfil', t.perfil);
  setElementText('linkAdmin', t.admin);
  setElementText('linkEstoque', t.estoque);
  setElementText('btnEntrarNav', t.entrar);

  setElementText('heroTitulo', t.heroTitle);
  setElementText('heroDesc', t.heroDesc);
  setElementText('feat1', t.feat1);
  setElementText('feat2', t.feat2);
  setElementText('feat3', t.feat3);
  setElementText('btnHeroCriar', t.btnCriarConta);
  setElementText('btnHeroDemo', t.btnDemo);

  setElementText('collabTitulo', t.collabTitle);
  setElementText('collabDesc', t.collabDesc);
  setElementText('btnContribuir', t.btnContribuir);

  setElementText('tabBtnMarket', t.tabMarket);
  setElementText('tabBtnTrocas', t.tabTrocas);
  setElementText('txtMinhasProps', t.minhasPropostas);

  const inputBusca = document.getElementById('inputBusca');
  if (inputBusca) inputBusca.placeholder = t.buscaPlace;

  setElementText('optTodosAlbuns', t.todosAlbuns);
  setElementText('optQualquerDist', t.qualquerDist);
  setElementText('tituloMarketplace', t.tituloMarket);
  setElementText('tituloTrocas', t.tituloTrocas);
  setElementText('txtCarregandoMarket', t.carregandoMarket);
  setElementText('txtCarregandoTrocas', t.carregandoTrocas);

  setElementText('footerAjudar', t.footerAjudar);
  setElementText('footerContato', t.footerContato);
  setElementText('footerPlataforma', t.footerPlat);
  setElementText('footerDev', t.footerDev);

  setElementText('authTitulo', t.authTitle);
  setElementText('authSub', t.authSub);
  setElementText('authOu', t.authOu);
  
  const authEmail = document.getElementById('authEmail');
  if (authEmail) authEmail.placeholder = t.placeEmail;
  
  const authSenha = document.getElementById('authSenha');
  if (authSenha) authSenha.placeholder = t.placeSenha;

  setElementText('btnLoginEmail', t.btnLogin);
  setElementText('btnCadEmail', t.btnCad);
  setElementText('btnCloseAuth', t.btnClose);

  const selectIdioma = document.getElementById('selectIdioma');
  if (selectIdioma) selectIdioma.value = idiomaAtual;
  
  const selectMoeda = document.getElementById('selectMoeda');
  if (selectMoeda) selectMoeda.value = moedaAtual;
}
